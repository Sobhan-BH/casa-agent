"""WAF / CDN / Proxy detection — passive fingerprinting (wafw00f-inspired).

Detects edge protection from evidence the target already returns: response
headers, body markers of challenge pages, and cookie names. No active probing
(no fake attack payloads — that is exploit-adjacent and out of CASA's scope).

Why it matters: a WAF in front of the target changes how findings should be
interpreted (mitigation in depth) and enriches the attack surface map.
"""
from __future__ import annotations

import re
from typing import Any

from agent.core.context import AssessmentContext
from agent.core.finding import make_finding, make_fingerprint
from agent.core.interfaces import AssessmentModule

# name -> (header regex map, body regexes, cookie-name regexes)
# Curated from public signature sets (wafw00f / fingerprinting write-ups).
